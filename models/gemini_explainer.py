"""
================================================================================
 Multimodal RCA Engine — Gemini AI Integration Module
================================================================================
This module uses the Gemini API to explain anomaly diagnosis results in natural
language, generate structured remediation recommendations, and analyze log data.

Usage:
    from models.gemini_explainer import GeminiExplainer
    explainer = GeminiExplainer()
    explanation = explainer.explain_anomaly(scenario_info, diagnosis)
"""

import os
import json
from pathlib import Path
from typing import Optional

try:
    from dotenv import load_dotenv
    load_dotenv(Path(__file__).parent.parent / ".env")
except ImportError:
    pass  # if python-dotenv is not installed, environment variables are used directly

try:
    import google.generativeai as genai
    GEMINI_AVAILABLE = True
except ImportError:
    GEMINI_AVAILABLE = False


class GeminiExplainer:
    """
    Class that generates anomaly explanations and remediation recommendations
    using the Gemini API.

    Features:
    - Explains an anomaly scenario in natural language (Turkish or English)
    - Analyzes log data and produces a summary
    - Expands and prioritizes remediation steps
    - Free-text question-answering support (RCA chatbot)
    """

    MODEL_NAME = "gemini-2.0-flash"

    def __init__(self, api_key: Optional[str] = None, language: str = "tr"):
        """
        Parameters:
            api_key  : Gemini API key. If None, read from the GEMINI_API_KEY env variable.
            language : Output language — 'tr' (Turkish) or 'en' (English).
        """
        if not GEMINI_AVAILABLE:
            raise ImportError(
                "The google-generativeai package is not installed. "
                "Run: pip install google-generativeai"
            )

        self.api_key = api_key or os.environ.get("GEMINI_API_KEY", "")
        if not self.api_key:
            raise ValueError(
                "Gemini API key not found. "
                "Set the GEMINI_API_KEY environment variable or add it to the .env file."
            )

        genai.configure(api_key=self.api_key)
        self.model    = genai.GenerativeModel(self.MODEL_NAME)
        self.language = language
        print(f"[GeminiExplainer] Model loaded: {self.MODEL_NAME} | Language: {language}")

    # ─────────────────────────────────────────────────────────────────────────
    # 1. ANOMALY EXPLANATION
    # ─────────────────────────────────────────────────────────────────────────
    def explain_anomaly(self, scenario_info: dict, diagnosis: dict) -> str:
        """
        Produce a natural-language explanation for the detected anomaly.

        Parameters:
            scenario_info : Scenario catalog information (id, name_tr, layer_tr, etc.)
            diagnosis     : Dictionary returned by build_diagnosis_message()

        Returns:
            The explanation text generated by Gemini
        """
        sc_id      = scenario_info.get("id", "UNKNOWN")
        if self.language == "tr":
            sc_name    = scenario_info.get("name_tr", scenario_info.get("name", ""))
            layer      = scenario_info.get("layer_tr", scenario_info.get("layer", ""))
            root_cause = scenario_info.get("root_cause_tr", scenario_info.get("root_cause", ""))
        else:
            sc_name    = scenario_info.get("name", scenario_info.get("name_tr", ""))
            layer      = scenario_info.get("layer", scenario_info.get("layer_tr", ""))
            root_cause = scenario_info.get("root_cause", scenario_info.get("root_cause_tr", ""))
        severity   = scenario_info.get("severity", "medium")
        atype      = scenario_info.get("anomaly_type", "")
        params     = ", ".join(scenario_info.get("detection_params", []))
        risk       = diagnosis.get("risk", "")
        sla        = diagnosis.get("sla", "")

        if self.language == "tr":
            prompt = f"""
Sen bir kıdemli DevOps/SRE mühendisisin. Asağıda bir altyapı anomalisinin
otomatik ML tespiti sonuçları verilmiştir. Bu sonuçları sistem yöneticisi
için anlaşılır, yapıcı ve eyleme dönüştürülebilir Türkçe bir açıklama
olarak yaz. Jargonu açıkla, neden önemli olduğunu belirt, ne olabilir sorusuna
yanıt ver. Madde madde degil, akıcı paragraf halinde yaz.

TESPIT SONUCLARI:
- Senaryo Kodu     : {sc_id}
- Senaryo Adi      : {sc_name}
- Altyapi Katmani  : {layer}
- Kok Neden        : {root_cause}
- Anomali Siddet   : {severity}
- Anomali Tipi     : {atype}
- Tetikleyici Metrikler: {params}
- Risk Skoru       : {risk}
- Mudahale SLA     : {sla}

Lütfen 3-4 cümlelik, teknik ama anlaşılır bir Türkçe açıklama yaz.
"""
        else:
            prompt = f"""
You are a senior DevOps/SRE engineer. Below are the results of an automated
ML anomaly detection. Write a clear, constructive, and actionable English
explanation for the system administrator. Explain the jargon, why it matters,
and what could happen if not addressed. Write in flowing paragraphs, not bullet points.

DETECTION RESULTS:
- Scenario Code    : {sc_id}
- Scenario Name    : {sc_name}
- Infrastructure Layer: {layer}
- Root Cause       : {root_cause}
- Severity         : {severity}
- Anomaly Type     : {atype}
- Triggering Metrics: {params}
- Risk Score       : {risk}
- Response SLA     : {sla}

Please write a 3-4 sentence technical but understandable explanation.
"""

        response = self.model.generate_content(prompt)
        return response.text.strip()

    # ─────────────────────────────────────────────────────────────────────────
    # 2. REMEDIATION STEP EXPANSION
    # ─────────────────────────────────────────────────────────────────────────
    def expand_remediation(self, scenario_info: dict, base_steps: list) -> str:
        """
        Expand and detail the base remediation steps with Gemini.

        Parameters:
            scenario_info : Scenario information
            base_steps    : List of base remediation steps coming from the YAML

        Returns:
            An expanded, prioritized remediation plan (text)
        """
        if self.language == "tr":
            sc_name    = scenario_info.get("name_tr", scenario_info.get("name", ""))
            layer      = scenario_info.get("layer_tr", scenario_info.get("layer", ""))
            root_cause = scenario_info.get("root_cause_tr", scenario_info.get("root_cause", ""))
        else:
            sc_name    = scenario_info.get("name", scenario_info.get("name_tr", ""))
            layer      = scenario_info.get("layer", scenario_info.get("layer_tr", ""))
            root_cause = scenario_info.get("root_cause", scenario_info.get("root_cause_tr", ""))
        severity   = scenario_info.get("severity", "medium")
        steps_str  = "\n".join(f"  - {s}" for s in base_steps)

        if self.language == "tr":
            prompt = f"""
Sen bir kıdemli SRE mühendisisin ve asağıdaki altyapı anomalisini cözmek
zorundasın. Verilen temel çözüm adımlarını alarak her biri icin:
1) Ne yapılacağını net belirt
2) Nasıl yapılacağını (komut veya prosedür) açıkla
3) Hangi riski azalttığını belirt
4) Doğrulama kriteri ekle

Cıktı formatı: Numaralı liste, her adim 3-4 cümle.

ANOMALI:
- Senaryo: {sc_name}
- Katman : {layer}
- Kok Neden: {root_cause}
- Siddet: {severity}

TEMEL COZUM ADIMLARI:
{steps_str}
"""
        else:
            prompt = f"""
You are a senior SRE engineer and must resolve the following infrastructure anomaly.
Take the provided base remediation steps and for each one:
1) State clearly what to do
2) Explain how to do it (command or procedure)
3) State which risk it mitigates
4) Add a verification criterion

Output format: Numbered list, each step 3-4 sentences.

ANOMALY:
- Scenario : {sc_name}
- Layer    : {layer}
- Root Cause: {root_cause}
- Severity : {severity}

BASE REMEDIATION STEPS:
{steps_str}
"""

        response = self.model.generate_content(prompt)
        return response.text.strip()

    # ─────────────────────────────────────────────────────────────────────────
    # 3. LOG ANALYSIS
    # ─────────────────────────────────────────────────────────────────────────
    def analyze_logs(self, log_features: dict, scenario_id: str) -> str:
        """
        Interpret the log feature vector and produce a summary.

        Parameters:
            log_features : {'log_error_count': 45, 'log_warn_ratio': 0.32, ...}
            scenario_id  : The detected scenario code

        Returns:
            A natural-language interpretation of the log state
        """
        feats_str = "\n".join(f"  {k}: {v}" for k, v in log_features.items())

        if self.language == "tr":
            prompt = f"""
Asağıdaki log ozellikleri bir altyapı anomali tespit sisteminden alınmıştır
({scenario_id} senaryosu tespit edildi). Bu sayısal log metriklerini
yorumla: hangi degerler anormal, neden tehlikeli, ve operasyonel
etkisi ne olabilir? 2-3 cümlelik kısa ve net Türkce yorum yaz.

LOG OZELLIKLERI:
{feats_str}
"""
        else:
            prompt = f"""
The following log features were extracted from an infrastructure anomaly detection
system ({scenario_id} scenario detected). Interpret these numerical log metrics:
which values are abnormal, why they are dangerous, and what the operational
impact could be. Write a concise 2-3 sentence English interpretation.

LOG FEATURES:
{feats_str}
"""

        response = self.model.generate_content(prompt)
        return response.text.strip()

    # ─────────────────────────────────────────────────────────────────────────
    # 4. FREE-TEXT QUESTION ANSWERING (RCA CHATBOT)
    # ─────────────────────────────────────────────────────────────────────────
    def chat(self, question: str, context: Optional[dict] = None) -> str:
        """
        Free-text question answering in the context of the RCA Engine.

        Parameters:
            question : The user's question
            context  : Optional — the current diagnosis context dictionary

        Returns:
            Gemini's response
        """
        system_ctx = (
            "Sen Multimodal RCA Engine icin bir yapay zeka asistanisin. "
            "Altyapı anomalisi tespiti, kök neden analizi ve SRE konularında "
            "uzmansin. Kısa, net ve eyleme dönüştürülebilir yanıtlar ver."
            if self.language == "tr" else
            "You are an AI assistant for the Multimodal RCA Engine. "
            "You specialize in infrastructure anomaly detection, root cause analysis, "
            "and SRE practices. Give concise, clear, and actionable responses."
        )

        ctx_label = "MEVCUT TESHIS BAGLAMI" if self.language == "tr" else "CURRENT DIAGNOSIS CONTEXT"
        q_label   = "SORU" if self.language == "tr" else "QUESTION"

        ctx_str = ""
        if context:
            ctx_str = f"\n\n{ctx_label}:\n{json.dumps(context, ensure_ascii=False, indent=2)}"

        prompt = f"{system_ctx}{ctx_str}\n\n{q_label}: {question}"
        response = self.model.generate_content(prompt)
        return response.text.strip()

    # ─────────────────────────────────────────────────────────────────────────
    # 5. FULL REPORT GENERATION
    # ─────────────────────────────────────────────────────────────────────────
    def generate_full_report(self, results: list) -> str:
        """
        Produce a comprehensive executive summary report from all diagnosis results.

        Parameters:
            results : A list of dictionaries, one per diagnosis result

        Returns:
            An executive summary report (in markdown format)
        """
        anomalies = [r for r in results if r.get("is_anomaly")]
        normals   = [r for r in results if not r.get("is_anomaly")]

        sev_counts = {}
        for r in anomalies:
            sev = r.get("severity", "unknown")
            sev_counts[sev] = sev_counts.get(sev, 0) + 1

        sc_list = "\n".join(
            f"  - {r.get('scenario_id','?')} ({r.get('layer','?')}): "
            f"{r.get('sc_info', {}).get('name_tr', r.get('scenario_id',''))} "
            f"[{r.get('severity','?')}]"
            for r in anomalies[:15]
        )

        if self.language == "tr":
            prompt = f"""
Sen bir kıdemli SRE mühendisin ve asağıdaki altyapı teshis oturumunu
yönetici için kapsamli bir Türkce ozet rapor olarak yaz. Rapor sorunları
öncelik sirasına göre listelesin, genel risk durumunu değerlendirsin
ve kısa vadeli (bu hafta) ile uzun vadeli (bu ay) eylem planlarini önersin.
Markdown formatında yaz.

OTURUM OZETI:
- Toplam test: {len(results)}
- Normal: {len(normals)}
- Anomali: {len(anomalies)}
- Kritik: {sev_counts.get('critical', 0)}
- Yuksek: {sev_counts.get('high', 0)}
- Orta: {sev_counts.get('medium', 0)}

TESPIT EDILEN ANOMALILER:
{sc_list}
"""
        else:
            prompt = f"""
You are a senior SRE engineer. Write a comprehensive executive summary report
in English for the following infrastructure diagnosis session. The report should
list issues in priority order, assess the overall risk posture, and propose
short-term (this week) and long-term (this month) action plans. Write in markdown.

SESSION SUMMARY:
- Total tests   : {len(results)}
- Normal        : {len(normals)}
- Anomalies     : {len(anomalies)}
- Critical      : {sev_counts.get('critical', 0)}
- High          : {sev_counts.get('high', 0)}
- Medium        : {sev_counts.get('medium', 0)}

DETECTED ANOMALIES:
{sc_list}
"""

        response = self.model.generate_content(prompt)
        return response.text.strip()
